"""Markdown incident report rendering."""

from __future__ import annotations

from ..schemas import Investigation


def render_markdown(inv: Investigation) -> str:
    lines: list[str] = []
    w = lines.append

    w(f"# Incident Report — {inv.id}")
    w("")
    if inv.simulated:
        w("> **Note:** This investigation ran against **simulated demo data**.")
        w("")
    w("| Field | Value |")
    w("|---|---|")
    w(f"| Incident ID | `{inv.id}` |")
    w(f"| Cloud provider | {inv.provider.upper()} |")
    w(f"| Affected resource | `{inv.resource_id or 'n/a'}` |")
    if inv.scenario_id:
        w(f"| Demo scenario | `{inv.scenario_id}` |")
    if inv.time_window:
        w(f"| Time window | {inv.time_window.start.isoformat()} → {inv.time_window.end.isoformat()} |")
    w(f"| Status | {inv.status} |")
    w(f"| Created | {inv.created_at.isoformat()} |")
    if inv.completed_at:
        w(f"| Completed | {inv.completed_at.isoformat()} |")
    if inv.report:
        w(f"| Severity assessment | {inv.report.severity_assessment} |")
        w(f"| Confidence | {inv.report.confidence} |")
        w(f"| Analysis engine | {inv.report.llm_provider} |")
    w("")
    w(f"**Question:** {inv.question}")
    w("")

    if inv.report:
        w("## Summary")
        w("")
        w(inv.report.summary)
        w("")

    w("## Investigation timeline")
    w("")
    w("| # | Tool | Input | Outcome | Duration |")
    w("|---|---|---|---|---|")
    for s in inv.steps:
        input_str = ", ".join(f"{k}={v}" for k, v in s.input.items()) or "—"
        outcome = s.output_summary or s.error or s.status
        w(f"| {s.index} | `{s.tool}` | {input_str} | {outcome} | {s.duration_ms or 0} ms |")
    w("")

    if inv.evidence:
        w("## Evidence")
        w("")
        for ev in inv.evidence:
            sim = " _(simulated)_" if ev.simulated else ""
            w(f"- **{ev.id}** ({ev.type}, via `{ev.source_tool}`){sim}: {ev.title} — {ev.summary}")
        w("")

    if inv.report:
        r = inv.report
        w("## Observed facts")
        w("")
        for f in r.observed_facts or []:
            refs = ", ".join(f"`{i}`" for i in f.evidence_ids)
            w(f"- {f.statement}" + (f" (evidence: {refs})" if refs else ""))
        if not r.observed_facts:
            w("- No significant findings in the retrieved telemetry.")
        w("")
        w("## Possible causes")
        w("")
        for c in r.possible_causes or []:
            w(f"- **{c.cause}** — _{c.likelihood}_. {c.rationale}")
        if not r.possible_causes:
            w("- No cause could be established from the available evidence.")
        w("")
        w("## Recommended remediation")
        w("")
        for rec in r.recommendations or []:
            w(f"- {rec.action} _(risk: {rec.risk})_ — {rec.rationale}")
        w("")
        w("## Limitations")
        w("")
        for lim in r.limitations:
            w(f"- {lim}")
        w("")

    if inv.error:
        w("## Error")
        w("")
        w(f"The investigation failed: {inv.error}")
        w("")

    w("---")
    w("_Generated by CloudOps AI Agent._")
    return "\n".join(lines) + "\n"
